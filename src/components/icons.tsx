/** The icon for each kind of trip guide. */
export function GuideIcon({
  id,
  ...props
}: IconProps & { id: "getting-there" | "where-to-stay" | "when-to-go" }) {
  switch (id) {
    case "getting-there":
      return <RouteIcon {...props} />;
    case "where-to-stay":
      return <BedIcon {...props} />;
    case "when-to-go":
      return <CalendarIcon {...props} />;
  }
}
